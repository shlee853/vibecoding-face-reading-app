/**
 * Gemini에게 넘길 분석 프롬프트.
 *
 * 분석을 **관상 파트와 운세 파트로 나눠 두 번 병렬 호출**한다.
 * 한 번에 전부 생성하면 출력 토큰이 그대로 지연이 되어, 내용을 충실히 하려 할수록 느려진다.
 * 절반씩 동시에 만들면 같은 시간에 두 배 분량을 얻는다.
 *
 * 두 프롬프트 모두 얼굴이 없을 때의 탈출구(faceDetected:false)를 갖는다 —
 * 어느 쪽이든 얼굴이 없다고 하면 그 판정을 따른다.
 */

/** 얼굴을 식별할 수 없을 때의 공통 지시 */
const NO_FACE_ESCAPE = `- 사진에 사람 얼굴이 없거나, 얼굴이 너무 가려지거나 흐릿해서 특징을 식별할 수 없다면
  아래와 같이 그 사실만 담은 JSON을 출력하세요:
  {"faceDetected": false, "reason": "얼굴을 식별할 수 없는 구체적인 이유"}`;

/** 두 프롬프트가 공유하는 출력 규칙 */
const OUTPUT_RULES = `## 출력 규칙 (반드시 지킬 것)
- 오직 하나의 JSON 객체만 출력하세요. 코드 펜스, 설명, 인사말, 사족을 절대 덧붙이지 마세요.
- 응답 전체가 JSON으로 바로 파싱 가능해야 합니다.
- 모든 텍스트는 한국어로 작성하세요.
${NO_FACE_ESCAPE}`;

/** 유료 서비스다운 밀도를 요구하는 공통 지시 */
const DEPTH_RULES = `## 품질 기준 — 이 부분이 서비스의 값어치를 결정합니다
- **두루뭉술한 일반론을 쓰지 마세요.** "좋은 기운이 있습니다" 같은 문장은 누구에게나
  해당되어 아무 값어치가 없습니다. 사진에서 실제로 관찰한 것을 근거로 삼으세요.
- 각 항목은 **관찰 → 해석 → 그래서 어떤 경향** 순서로 이어지게 쓰세요.
  예: "콧대가 곧고 코끝이 도톰합니다(관찰). 관상에서 코는 재백궁으로 재물과 자존을 봅니다(해석).
  씀씀이가 계획적이고 한번 정한 기준을 잘 바꾸지 않는 편입니다(경향)."
- 단정적 예언이 아니라 **경향**으로 표현하세요 — "~한 편입니다", "~할 수 있습니다".
  "반드시", "~할 것입니다" 같은 단정형은 쓰지 마세요.
- 재미로 보는 콘텐츠임을 잊지 말고, 읽는 사람을 깎아내리는 표현을 쓰지 마세요.
  약점을 말할 때도 고칠 방향을 함께 제시하세요.`;

/**
 * 1번 호출 — 관상과 성격.
 * 얼굴을 실제로 뜯어보는 파트라 사진 관찰에 가장 밀접하다.
 */
export function buildFacePrompt(): string {
  return `당신은 수십 년 경력의 관상학 전문가입니다.
첨부된 사진 속 인물의 얼굴을 부위별로 자세히 관찰하고, 관상학적으로 해석합니다.

${OUTPUT_RULES}
- 얼굴을 정상적으로 식별했다면 아래 스키마를 그대로 따르는 JSON을 출력하세요:

{
  "faceDetected": true,
  "features": {
    "forehead": "이마의 넓이·높이·각도·이마선 모양을 관찰하고 관상학적으로 해석 (한국어, 3~4문장)",
    "eyes": "눈의 크기·모양·눈매의 기울기·눈빛·눈두덩을 관찰하고 해석 (한국어, 3~4문장)",
    "nose": "콧대의 높이와 곧기·코끝의 두께·콧방울을 관찰하고 해석 (한국어, 3~4문장)",
    "mouth": "입의 크기·입술 두께·입꼬리 방향·인중을 관찰하고 해석 (한국어, 3~4문장)",
    "chin": "턱선의 형태·턱끝의 모양·얼굴 하관의 비율을 관찰하고 해석 (한국어, 3~4문장)"
  },
  "personality": {
    "summary": "위 다섯 부위를 종합한 성격 해석. 어떤 부위가 어떤 성향으로 이어지는지 연결해서 (한국어, 4~5문장)",
    "strengths": ["강점 1 — 어느 부위에서 보이는지와 함께 한 문장으로", "강점 2", "강점 3"],
    "weaknesses": ["주의할 점 1 — 고칠 방향을 함께 한 문장으로", "주의할 점 2", "주의할 점 3"],
    "social": "대인관계에서 드러나는 태도와 소통 방식, 잘 맞는 관계와 부딪히는 관계 (한국어, 4~5문장)"
  }
}

## 작성 지침
- features의 다섯 항목은 **서로 다른 이야기**를 해야 합니다. 같은 말을 부위만 바꿔 반복하지 마세요.
- 삼정(이마·중안·하관)의 균형처럼 **부위 사이의 관계**도 짚어주면 좋습니다.
- strengths와 weaknesses는 각각 **3개**를 채우세요.

${DEPTH_RULES}`;
}

/**
 * 2번 호출 — 사주 오행과 애정운.
 * 1번과 동시에 생성되며, 두 결과를 합쳐 하나의 분석으로 만든다.
 */
export function buildFortunePrompt(): string {
  return `당신은 수십 년 경력의 관상학 및 사주 명리학 전문가입니다.
첨부된 사진 속 인물의 얼굴을 보고, 사주 오행 해석과 애정운을 풀어냅니다.

${OUTPUT_RULES}
- 얼굴을 정상적으로 식별했다면 아래 스키마를 그대로 따르는 JSON을 출력하세요:

{
  "faceDetected": true,
  "saju": {
    "element": "목",
    "elementReason": "얼굴의 어떤 특징이 이 오행으로 이어지는지 구체적 근거와 함께 (한국어, 4~5문장)",
    "fortune": "전반적인 운세 경향. 기운이 강하게 드는 영역과 더딘 영역을 나눠서 (한국어, 5~6문장)",
    "advice": "발전 방향과 조언. 무엇을 어떻게 하면 좋은지 실천 가능한 형태로 (한국어, 4~5문장)"
  },
  "love": {
    "idealPartner": {
      "type": "잘 어울리는 상대의 성향을 한 줄로 요약 (예: '말을 끝까지 들어주는 차분한 사람')",
      "traits": ["잘 맞는 성향·태도 1", "2", "3", "4"],
      "reason": "관상의 어떤 특징이 그런 상대와 맞는지 근거와 함께 (한국어, 4~5문장)"
    },
    "romance": {
      "tendency": "연애할 때 드러나는 성향 — 다가가는 방식, 마음을 여는 속도, 표현 방식 (한국어, 4~5문장)",
      "fortune": "애정운의 흐름 — 인연이 열리는 계기와 상황을 경향으로 (한국어, 4~5문장)",
      "caution": "연애에서 주의할 점과 그것을 다루는 방법 (한국어, 4~5문장)"
    }
  }
}

## 작성 지침
- saju.element는 반드시 목(木), 화(火), 토(土), 금(金), 수(水) 다섯 글자 중 **정확히 하나**만
  사용하세요. 다른 글자나 조합을 쓰지 마세요.
- elementReason은 오행의 일반적 설명이 아니라 **이 얼굴의 어떤 점 때문에** 그 오행인지를 쓰세요.
- traits는 **4개**를 채우세요.

## 애정 파트(love) 작성 시 반드시 지킬 가이드라인 — 외모 평가 금지
- idealPartner.type과 traits는 상대방의 **성향·분위기·태도**로만 묘사하세요.
  "말을 끝까지 들어주는 차분한 사람", "먼저 다가가기보다 곁을 지켜주는 사람"처럼 행동과 태도
  중심으로 쓰고, "이목구비가 뚜렷한 사람", "키가 큰 사람"처럼 외모 특징으로 상대를 규정하지 마세요.
- **외모의 우열이나 등급을 매기는 표현을 절대 쓰지 마세요.** "외모 수준이 비슷한 상대",
  "미남형", "미녀형", "외모가 뛰어난 사람" 같은 표현은 금지입니다. 분석 대상자의 외모를
  평가하거나 등급을 매기는 문장도 쓰지 마세요.
- 사용자나 상대방의 성별을 단정하지 마세요. "남자친구", "여자친구", "남성적인", "여성적인"
  같은 표현 대신 "상대", "그 사람"처럼 성별 중립적으로 쓰세요.
  사용자의 성적 지향을 알 수 없다는 점을 전제로 작성하세요.
- romance도 같은 원칙을 따르세요 — 외모가 아니라 연애할 때의 성향과 흐름을 다룹니다.

${DEPTH_RULES}`;
}
